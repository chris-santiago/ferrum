# 3. deny_unknown_fields on the wire round-trip (ChartSpec.from_json)
# ===========================================================================


def _base_spec_json() -> dict:
    return json.loads(ChartSpec(mark="point", x="a", y="b").to_json())


def test_transform_typo_key_is_rejected() -> None:
    """A misspelled transform field raises ValueError (deny_unknown_fields ON).

    Path: ``crates/.../transform/*.rs`` structs carry ``#[serde(deny_unknown_fields)]``.
    A ``predicat`` typo on a filter transform must surface as an ``unknown field``
    error, NOT a silent drop.
    """
    df = pl.DataFrame({"a": [1.0, 2.0, 3.0], "b": [4.0, 5.0, 6.0]})
    base = fm.Chart(df).transform(fm.transform_filter("a > 1")).mark_point().encode(x="a", y="b")
    j = json.loads(base.to_spec().to_json())
    j["transforms"][0]["predicat"] = "a > 1"  # typo of "predicate"
    with pytest.raises(ValueError, match="unknown field"):
        ChartSpec.from_json(json.dumps(j))


def test_unknown_transform_variant_is_rejected() -> None:
    """An unknown transform ``type`` value raises (tagged-enum variant guard).

    Path: serde tagged-enum deserialise on the transform list.  ``"flilter"`` is
    not a known variant.
    """
    df = pl.DataFrame({"a": [1.0, 2.0, 3.0], "b": [4.0, 5.0, 6.0]})
    base = fm.Chart(df).transform(fm.transform_filter("a > 1")).mark_point().encode(x="a", y="b")
    j = json.loads(base.to_spec().to_json())
    j["transforms"][0]["type"] = "flilter"
    with pytest.raises(ValueError, match="unknown variant"):
        ChartSpec.from_json(json.dumps(j))


def test_per_channel_axis_style_typo_is_rejected() -> None:
    """A misspelled per-channel ``axis`` style key raises (AxisStyleSpec guards it).

    Path: ``EncodingSpec.axis`` is typed against ``AxisStyleSpec`` which has
    ``#[serde(deny_unknown_fields)]``.  ``labl_angle`` must fail loud.
    """
    df = pl.DataFrame({"a": [1.0, 2.0, 3.0], "b": [4.0, 5.0, 6.0]})
    base = fm.Chart(df).mark_point().encode(x=fm.X("a", axis=fm.Axis(label_angle=10)), y="b")
    j = json.loads(base.to_spec().to_json())
    j["encoding"]["x"]["axis"]["labl_angle"] = 20  # typo of label_angle
    with pytest.raises(ValueError, match="unknown field"):
        ChartSpec.from_json(json.dumps(j))


def test_encoding_channel_typo_key_is_rejected() -> None:
    """A misspelled encoding-channel key (``typ``) raises, not silently dropped.

    Path: ``EncodingSpec`` (spec/encoding.rs) carries struct-level
    ``#[serde(deny_unknown_fields)]`` (S4FIX2), so ``{"field": "a", "typ": "Q"}``
    (typo of ``type``) fails loud as an ``unknown field`` error rather than
    dropping the intended type.  Completes the no-silent-drop seam so the
    channel-key path matches the per-channel axis-style path above.
    """
    j = _base_spec_json()
    j["encoding"]["x"]["typ"] = "Q"  # typo of the "type" wire key
    with pytest.raises(ValueError, match="unknown field"):
        ChartSpec.from_json(json.dumps(j))


def test_scale_dict_typo_key_is_tolerated_documented_exception() -> None:
    """A misspelled scale key (``clammp``) is TOLERATED (documented exception).

    Path: ``ScaleSpec`` deserialise.  Unlike ``EncodingSpec``/``ChartSpec``,
    ``ScaleSpec`` is an internally-tagged enum whose every continuous variant
    embeds ``ContinuousScaleCommon`` via ``#[serde(flatten)]``.  serde cannot
    enforce ``deny_unknown_fields`` through a flattened / internally-tagged shape,
    so a ``clammp`` typo (of ``clamp``) inside a ``scale`` sub-dict is accepted
    and silently dropped.  This is a structural serde constraint, documented on
    the ``ScaleSpec`` doc comment — NOT a fail-loud surface.  This test pins that
    tolerated-drop so a future "fix" that breaks the round-trip is caught.
    """
    df = pl.DataFrame({"a": [1.0, 2.0, 3.0], "b": [4.0, 5.0, 6.0]})
    base = fm.Chart(df).mark_point().encode(x=fm.X("a", scale=fm.LinearScale()), y="b")
    j = json.loads(base.to_spec().to_json())
    j["encoding"]["x"]["scale"]["clammp"] = True  # typo of clamp
    # Tolerated: the flattened ScaleSpec cannot deny, so this round-trips and the
    # typo'd key is dropped (no error).
    spec = ChartSpec.from_json(json.dumps(j))
    round_tripped = json.loads(spec.to_json())
    assert "clammp" not in round_tripped["encoding"]["x"]["scale"]


def test_top_level_chartspec_typo_key_is_rejected() -> None:
    """A misspelled top-level ChartSpec key (``marrk``) raises, not dropped.

    Path: top-level ``ChartSpec`` carries ``#[serde(deny_unknown_fields)]``
    (S4FIX2), so a ``marrk`` typo (of ``mark``) fails loud as an ``unknown
    field`` error rather than being silently dropped.
    """
    j = _base_spec_json()
    j["marrk"] = "point"  # typo of "mark"; the real "mark" stays "point"
    with pytest.raises(ValueError, match="unknown field"):
        ChartSpec.from_json(json.dumps(j))


