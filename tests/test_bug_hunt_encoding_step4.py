# 4. min_band/max_band alias resolution — VALUE edges (type, negative, zero)
#    (The cross-surface warn/raise/None edges are covered by
#     tests/test_cohesion_band_alias_and_primitive_marks.py; here we probe the
#     numeric value-domain edges that file does not exercise.)
# ===========================================================================

_BAND_SURFACES = [
    ("Axis", lambda **kw: Axis(**kw)),
    ("AxisConfig", lambda **kw: AxisConfig(**kw)),
]
_BAND_IDS = ["Axis", "AxisConfig"]


@pytest.mark.parametrize("label,build", _BAND_SURFACES, ids=_BAND_IDS)
@pytest.mark.parametrize("bound", ["min", "max"])
def test_band_zero_is_preserved_not_treated_as_unset(label, build, bound) -> None:  # noqa: ARG001
    """``<bound>_band=0`` (falsy but supplied) must survive as ``0``, not vanish.

    Path: ``_resolve_band_alias`` returns ``canonical_value`` when no alias is
    given; ``0`` is a legitimate band bound.  A naive ``if value:`` truthiness
    check would drop it.  Also confirms ``to_dict`` keeps it (no default filtering
    for band fields).
    """
    obj = build(**{f"{bound}_band": 0})
    assert getattr(obj, f"{bound}_band") == 0
    assert obj.to_dict().get(f"{bound}_band") == 0


@pytest.mark.parametrize("label,build", _BAND_SURFACES, ids=_BAND_IDS)
@pytest.mark.parametrize("bound", ["min", "max"])
def test_band_negative_value_passes_through(label, build, bound) -> None:  # noqa: ARG001
    """A negative band value is accepted at the Python layer (no validation gate).

    Path: ``_resolve_band_alias`` does not range-check; pins that the Python
    surface forwards ``-5`` verbatim (the renderer, not the value class, owns any
    sign policy).  This documents the *absence* of a Python-side guard.
    """
    obj = build(**{f"{bound}_band": -5.0})
    assert getattr(obj, f"{bound}_band") == -5.0


@pytest.mark.parametrize("label,build", _BAND_SURFACES, ids=_BAND_IDS)
@pytest.mark.parametrize("bound", ["min", "max"])
def test_band_non_number_alias_passes_through_untyped(label, build, bound) -> None:
    """A non-number band ALIAS value rides through resolution unchecked + warns.

    Path: ``_resolve_band_alias`` only checks the ``_MISSING`` sentinel and the
    double-supply conflict — it does NOT type-check the value.  A string passed
    under the deprecated alias warns (deprecation) and lands on the canonical
    field verbatim.  Pins that the resolver is value-agnostic (defers typing to
    serialization/Rust), which is a latent footgun worth documenting.
    """
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        obj = build(**{f"{bound}_extent": "not_a_number"})
    dep = [w for w in caught if issubclass(w.category, DeprecationWarning)]
    assert dep, f"{label}: alias supply must warn even for a bad value"
    assert getattr(obj, f"{bound}_band") == "not_a_number"


def test_band_alias_double_supply_raises_typeerror_not_valueerror() -> None:
    """Double-supply raises ``TypeError`` (not ValueError) — pin the exact type.

    Path: ``_resolve_band_alias`` raises ``TypeError`` when both canonical and
    alias are present.  Callers that ``except ValueError`` must NOT swallow this.
    """
    with pytest.raises(TypeError):
        Axis(min_band=5, min_extent=7)
    with pytest.raises(TypeError):
        AxisConfig(max_band=5, max_extent=7)
