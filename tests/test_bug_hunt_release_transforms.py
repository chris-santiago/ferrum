# ---------------------------------------------------------------------------
# top_k — T9 integer aggregation vs count semantics
# ---------------------------------------------------------------------------


def test_top_k_int_field_uses_aggregate_not_count():
    # field is the Int64 column itself. Groups: 10(x3,sum30), 100(x1,sum100),
    # 5(x2,sum10). Top-2 by SUM = {100, 10}; top-2 by COUNT = {10, 5}. If T9
    # regressed to count, value 5 would survive and 100 would be dropped.
    df = pl.DataFrame(
        {
            "score": pl.Series([10, 10, 10, 100, 5, 5], dtype=pl.Int64),
        }
    )
    t = transform_top_k(2, field="score", op="sum", sort="descending")
    chart = fm.Chart(df).mark_bar().encode(x="score:N", y="score:Q").transform(t)
    svg = _svg(chart)
    texts = _texts(svg)
    i = texts.index("score") if "score" in texts else len(texts)
    cats = {t for t in texts if t in ("5", "10", "100")}
    assert "100" in cats, f"top-2 by sum must keep 100; categories present: {cats}"
    assert "5" not in cats, f"top-2 by sum must drop 5 (lowest sum); categories: {cats}"


def test_top_k_n_larger_than_group_count_keeps_all():
    # n exceeds the number of distinct groups → keep everything, no panic.
    df = pl.DataFrame(
        {
            "cat": pl.Series(["a", "b", "c"], dtype=pl.Utf8),
            "v": pl.Series([1.0, 2.0, 3.0], dtype=pl.Float64),
        }
    )
    t = transform_top_k(10, field="cat", op="count", sort="descending")
    chart = fm.Chart(df).mark_bar().encode(x="cat:N", y="v:Q").transform(t)
    svg = _svg(chart)
    texts = _texts(svg)
    cats = {t for t in texts if t in ("a", "b", "c")}
    assert cats == {"a", "b", "c"}, f"n>groups must keep all; got {cats}"


