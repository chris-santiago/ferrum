class TestDomainParamInfNaN:
    # BUG: fm.param(value=[0, inf]) used as a scale domain raises a cryptic
    # low-level serde error ("params: expected value at line 1 column N")
    # because json.dumps emits the non-JSON token `Infinity`, which the Rust
    # serde_json deserializer rejects. The user gets no legible ferrum-level
    # diagnostic about an invalid domain bound.  Source: chart.py to_spec ->
    # json.dumps(params) ; crates/ferrum-core/src/spec/chart.rs new() params parse.
    def test_infinity_in_domain_param_gives_legible_error(self):
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x=fm.X("t", scale={"domain": fm.param("d", value=[0, math.inf])}), y=fm.Y("a"))
        )
        # We expect EITHER a clean render (inf clamped/ignored) OR a legible
        # ferrum error that names the parameter / domain. A raw serde
        # "expected value at line 1 column N" is neither.
        try:
            svg = c.to_svg()
        except Exception as exc:  # noqa: BLE001
            msg = str(exc)
            assert "expected value at line" not in msg, (
                f"Infinity domain bound surfaced as a raw serde parse error "
                f"instead of a legible ferrum diagnostic: {msg!r}"
            )
        else:
            assert "NaN" not in svg and "Infinity" not in svg

    # BUG: same root cause for NaN — json.dumps emits `NaN`, serde rejects it
    # with an opaque column-offset error rather than a domain-validation message.
    def test_nan_in_domain_param_gives_legible_error(self):
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(
                x=fm.X("t", scale={"domain": fm.param("d", value=[math.nan, 100])}), y=fm.Y("a")
            )
        )
        try:
            svg = c.to_svg()
        except Exception as exc:  # noqa: BLE001
            msg = str(exc)
            assert "expected value at line" not in msg, (
                f"NaN domain bound surfaced as a raw serde parse error instead "
                f"of a legible ferrum diagnostic: {msg!r}"
            )
        else:
            assert "NaN" not in svg


