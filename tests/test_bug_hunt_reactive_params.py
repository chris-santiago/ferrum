class TestConditionalStatic:
    def test_color_conditional_renders_otherwise_branch(self):
        """Static render of a color-conditional encoding (nothing selected).

        Post-FA-15 fix: a Color(field) conditional now builds a categorical legend.
        The data has 3 rows and 2 distinct values in 'c' ("x", "y"), so the SVG
        contains 3 data-mark circles plus 2 legend-symbol circles = 5 total.

        Static marks render in the default mark color; the conditional 'otherwise'
        hue is applied at interactive runtime, not baked into the static SVG.
        """
        df = _df()
        sel = fm.selection_point()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a", color=sel.when(fm.Color("c")).otherwise(value("#cccccc")))
        )
        svg = c.to_svg()
        assert "<svg" in svg
        # 3 data-mark circles + 2 legend-symbol circles (one per distinct "c" value).
        assert svg.count("<circle") == 5

    def test_opacity_conditional_channel_and_kinds(self):
        df = _df()
        sel = fm.selection_point()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a", opacity=fm.when(sel).then(1.0).otherwise(0.15))
        )
        cond = json.loads(c.to_json())["conditionals"][0]
        assert cond["channel"] == "opacity"
        assert cond["if_selected"] == {"kind": "opacity", "value": 1.0}
        assert cond["if_not"] == {"kind": "opacity", "value": 0.15}

    def test_size_conditional_numeric_kinds(self):
        df = _df()
        sel = fm.selection_point()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a", size=fm.when(sel).then(100).otherwise(20))
        )
        cond = json.loads(c.to_json())["conditionals"][0]
        assert cond["channel"] == "size"
        assert cond["if_selected"]["kind"] == "size"

    def test_multiple_conditionals_on_one_chart(self):
        """Two conditionals on distinct channels both serialize, both selections registered."""
        df = _df()
        s1 = fm.selection_point(name="s1")
        s2 = fm.selection_point(name="s2")
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(
                x="t",
                y="a",
                opacity=fm.when(s1).then(1.0).otherwise(0.2),
                size=fm.when(s2).then(80).otherwise(10),
            )
        )
        spec = json.loads(c.to_json())
        chans = {cd["channel"] for cd in spec["conditionals"]}
        assert chans == {"opacity", "size"}
        sel_names = {s["name"] for s in spec["selections"]}
        assert {"s1", "s2"} <= sel_names

    def test_conditional_only_selection_auto_registered(self):
        """A conditional via encode auto-registers its selection (no add_selection)."""
        df = _df()
        sel = fm.selection_point(name="auto")
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a", color=sel.when(fm.Color("c")).otherwise(value("#ccc")))
        )
        sel_names = {s["name"] for s in json.loads(c.to_json())["selections"]}
        assert "auto" in sel_names

    def test_resolve_encoding_value_rejects_raw_scalar(self):
        """A raw int (not value()-wrapped, not a channel) must raise TypeError."""
        with pytest.raises(TypeError, match="channel object"):
            _resolve_encoding_value(42)

    def test_when_rejects_variable_parameter(self):
        """fm.when(VariableParameter) must raise — a variable is not a predicate."""
        vp = fm.param("k", value=3)
        with pytest.raises(TypeError, match="fm.when"):
            fm.when(vp)

    def test_conditional_renders_without_nan(self):
        df = _df()
        sel = fm.selection_point()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a", color=sel.when(fm.Color("c")).otherwise(value("#cccccc")))
        )
        assert "NaN" not in c.to_svg()


