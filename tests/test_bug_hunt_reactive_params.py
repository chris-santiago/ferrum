"""Edge-case tests for the reactive-parameter / selection / conditional system (D6).

Generated by the bug-hunter agent. Targets the STATIC resolution and
serialization layer that runs without a browser:

- fm.param(value=) static domain substitution (numeric / string / bool / list)
- fm.when(...).then(...).otherwise(...) static resolution to the default branch
- scale={"domain": param} (domainParam) static rescale + degenerate domains
- transform_filter(param) crossfilter static contract (all rows kept)
- add_params dedup, name collisions, orphan params, wrong-typed args
- param -> spec -> from_json round-trip stability

Each test names the source code path it exercises. Tests proving a bug carry a
``# BUG:`` marker on the def line.
"""

from __future__ import annotations

import json
import math
import re

import polars as pl
import pytest

import ferrum as fm
from ferrum._core import ChartSpec
from ferrum.selection import _resolve_encoding_value, value


def _df() -> pl.DataFrame:
    return pl.DataFrame({"t": [10, 20, 30], "a": [1, 2, 3], "c": ["x", "y", "x"]})


def _params_of(spec) -> list:
    d = json.loads(spec.to_json())
    raw = d.get("params")
    if raw is None:
        return []
    if isinstance(raw, str):
        return json.loads(raw)
    return raw


def _cx(svg: str) -> list[float]:
    return [float(m) for m in re.findall(r'cx="([0-9.eE+-]+)"', svg)]


