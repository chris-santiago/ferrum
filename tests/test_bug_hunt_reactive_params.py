class TestRoundTrip:
    def test_domain_param_chart_round_trip_stable(self):
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x=fm.X("t", scale={"domain": fm.param("d", value=[0, 100])}), y=fm.Y("a"))
        )
        js = c.to_spec().to_json()
        rt = ChartSpec.from_json(js)
        assert rt.to_json() == js

    def test_domain_param_preserved_in_round_trip(self):
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x=fm.X("t", scale={"domain": fm.param("d", value=[0, 100])}), y=fm.Y("a"))
        )
        js = ChartSpec.from_json(c.to_spec().to_json()).to_json()
        assert "domainParam" in js
        # the variable value survives
        d = json.loads(js)
        params = d["params"]
        if isinstance(params, str):
            params = json.loads(params)
        d_param = next(p for p in params if p["name"] == "d")
        assert d_param["value"] == [0, 100]

    def test_selection_param_round_trip(self):
        df = _df()
        brush = fm.selection_interval(name="brush", encodings=["x"])
        c = fm.Chart(df).mark_point().encode(x=fm.X("t"), y=fm.Y("a")).add_selection(brush)
        js = c.to_spec().to_json()
        assert ChartSpec.from_json(js).to_json() == js

    def test_conditional_round_trip(self):
        df = _df()
        sel = fm.selection_point(name="s")
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a", opacity=fm.when(sel).then(1.0).otherwise(0.2))
        )
        js = c.to_spec().to_json()
        rt = ChartSpec.from_json(js)
        assert rt.to_json() == js

    def test_legend_bind_round_trip(self):
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a")
            .add_params(fm.param("lp", value=1, bind="legend"))
        )
        js = c.to_spec().to_json()
        rt_js = ChartSpec.from_json(js).to_json()
        assert rt_js == js
        params = json.loads(rt_js)["params"]
        if isinstance(params, str):
            params = json.loads(params)
        lp = next(p for p in params if p["name"] == "lp")
        assert lp.get("bind") == "legend"

    def test_param_free_chart_omits_params_key(self):
        """Byte-stability: a param-free chart never emits a params key."""
        df = _df()
        js = fm.Chart(df).mark_point().encode(x="t", y="a").to_spec().to_json()
        assert "params" not in js
