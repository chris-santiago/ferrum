class TestParamCollection:
    # BUG: a Selection and a VariableParameter sharing a name silently drop the
    # variable (first-seen = registered selection wins in _collect_params dedup).
    # When the variable was the source of a scale domainParam, the forced domain
    # value [0,100] is lost and the axis silently auto-infers a *different*
    # domain, corrupting the chart with no warning.
    # Source: chart.py _collect_params (selections iterated before _params /
    # domain refs; dedup by name keeps first-seen).
    # FIX: ferrum now raises ValueError on cross-kind name collision so the user
    # is told explicitly to rename one of the two objects.
    def test_selection_must_not_silently_shadow_domain_variable(self):
        df = _df()
        sel = fm.selection_interval(name="dup")
        chart = (
            fm.Chart(df)
            .mark_point()
            .encode(x=fm.X("t", scale={"domain": fm.param("dup", value=[0, 100])}), y=fm.Y("a"))
            .add_selection(sel)
        )
        # A cross-kind collision (Selection + VariableParameter sharing "dup")
        # must raise ValueError at serialization time — never silently diverge.
        with pytest.raises(ValueError, match="collision"):
            chart.to_svg()

    # BUG: add_params with a non-Parameter argument (e.g. a typo'd string or a
    # raw dict) is silently dropped by _collect_params' isinstance(p, Parameter)
    # filter. A user passing the wrong thing gets a silent no-op instead of a
    # TypeError.  Source: chart.py _collect_params `_add` guard.
    # FIX: add_params() now raises TypeError immediately at call time when a
    # non-Parameter argument is passed.
    def test_add_params_non_parameter_is_not_silently_dropped(self):
        df = _df()
        # A wrong-typed argument must raise TypeError at add_params() call time.
        with pytest.raises(TypeError, match="Parameter"):
            fm.Chart(df).mark_point().encode(x="t", y="a").add_params("not_a_param")

    def test_duplicate_variable_names_dedup_first_wins(self):
        """Two variables named 'k' → exactly one entry, first value wins."""
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a")
            .add_params(fm.param("k", value=1), fm.param("k", value=2))
        )
        params = _params_of(c.to_spec())
        ks = [p for p in params if p["name"] == "k"]
        assert len(ks) == 1
        assert ks[0]["value"] == 1

    def test_orphan_param_serializes_and_renders(self):
        """A param referenced by no encoding still serializes and renders."""
        df = _df()
        c = fm.Chart(df).mark_point().encode(x="t", y="a").add_params(fm.param("orphan", value=5))
        params = _params_of(c.to_spec())
        assert any(p["name"] == "orphan" for p in params)
        assert "<svg" in c.to_svg()

    def test_multiple_distinct_params(self):
        """Multiple distinct params all appear, none dropped."""
        df = _df()
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x="t", y="a")
            .add_params(fm.param("a1", value=1), fm.param("b2", value=2), fm.param("c3", value=3))
        )
        names = {p["name"] for p in _params_of(c.to_spec())}
        assert {"a1", "b2", "c3"} <= names

    def test_dedup_selection_and_domain_same_object(self):
        """A selection used as both a domain ref AND registered appears once."""
        df = _df()
        brush = fm.selection_interval(name="brush")
        c = (
            fm.Chart(df)
            .mark_point()
            .encode(x=fm.X("t", scale={"domain": brush}), y=fm.Y("a"))
            .add_selection(brush)
        )
        names = [p["name"] for p in _params_of(c.to_spec())]
        assert names.count("brush") == 1


